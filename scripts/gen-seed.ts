// Generates supabase/migrations/*_seed_lagos.sql from src/lib/areas.ts.
// Run: node --experimental-strip-types scripts/gen-seed.ts
import { writeFileSync } from "node:fs";
import { AREAS } from "../src/lib/areas.ts";
import { DISCO_AREAS } from "../src/lib/sources/discos.ts";
import { SOURCES } from "../src/lib/sources/registry.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
const lgas = [...new Set(AREAS.map((a) => a.lga))].sort();

const sql = `-- GENERATED by scripts/gen-seed.ts from src/lib/areas.ts. Do not edit by hand.
-- Reference geography only: coordinates are APPROXIMATE centre points. No electricity data is seeded.
set local search_path = lightdey, public;
insert into lightdey.states (id, name) values ('lagos', 'Lagos') on conflict do nothing;
insert into lightdey.cities (id, state_id, name) values ('lagos', 'lagos', 'Lagos') on conflict do nothing;
insert into lightdey.local_government_areas (id, state_id, name) values
${lgas.map((l) => `  (${q("lagos-" + slug(l))}, 'lagos', ${q(l)})`).join(",\n")}
on conflict do nothing;
insert into lightdey.neighbourhoods (id, name, city_id, lga_id, lat, lng, aliases) values
${AREAS.map((a) => `  (${q(a.id)}, ${q(a.name)}, 'lagos', ${q("lagos-" + slug(a.lga))}, ${a.lat}, ${a.lng}, array[${(a.aliases ?? []).map(q).join(", ")}]::text[])`).join(",\n")}
on conflict (id) do update set name = excluded.name, lga_id = excluded.lga_id, lat = excluded.lat, lng = excluded.lng, aliases = excluded.aliases, updated_at = now();
`;
writeFileSync(new URL("../supabase/migrations/20261113000100_seed_lagos.sql", import.meta.url), sql);

const nul = (v: string | number | null) => (v === null ? "null" : typeof v === "number" ? String(v) : q(v));
const sourcesSql = `-- GENERATED by scripts/gen-seed.ts from src/lib/sources/{registry,discos}.ts. Do not edit by hand.
-- Re-running keeps runtime fields (last_*_at) and lets the registry update descriptive fields.
set local search_path = lightdey, public;
insert into lightdey.sources (id, name, kind, trust_tier, coverage, url, credentials_required, refresh_interval_minutes, is_active, notes) values
${SOURCES.map((s) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.kind)}, ${s.tier}, ${q(s.coverage)}, ${nul(s.url)}, ${s.credentials ? "true" : "false"}, ${nul(s.refreshMinutes)}, ${s.active}, ${q(s.notes)})`).join(",\n")}
on conflict (id) do update set name = excluded.name, kind = excluded.kind, trust_tier = excluded.trust_tier, coverage = excluded.coverage, url = excluded.url,
  credentials_required = excluded.credentials_required, refresh_interval_minutes = excluded.refresh_interval_minutes, is_active = excluded.is_active, notes = excluded.notes;
delete from lightdey.disco_service_areas where neighbourhood_id not in (${DISCO_AREAS.map((d) => q(d.areaId)).join(", ")});
insert into lightdey.disco_service_areas (neighbourhood_id, disco_id, basis, source_url, verified_at) values
${DISCO_AREAS.map((d) => `  (${q(d.areaId)}, ${q(d.disco)}, ${q(d.basis)}, ${q(d.sourceUrl)}, '2026-11-13')`).join(",\n")}
on conflict (neighbourhood_id) do update set disco_id = excluded.disco_id, basis = excluded.basis, source_url = excluded.source_url, verified_at = excluded.verified_at;
`;
writeFileSync(new URL("../supabase/migrations/20261113010100_seed_sources.sql", import.meta.url), sourcesSql);
console.log(`Wrote ${AREAS.length} neighbourhoods across ${lgas.length} LGAs, ${SOURCES.length} sources, ${DISCO_AREAS.length} DisCo mappings`);
