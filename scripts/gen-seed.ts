// Generates supabase/migrations/*_seed_lagos.sql from src/lib/areas.ts.
// Run: node --experimental-strip-types scripts/gen-seed.ts
import { writeFileSync } from "node:fs";
import { AREAS } from "../src/lib/areas.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
const lgas = [...new Set(AREAS.map((a) => a.lga))].sort();

const sql = `-- GENERATED by scripts/gen-seed.ts from src/lib/areas.ts. Do not edit by hand.
-- Reference geography only: coordinates are APPROXIMATE centre points. No electricity data is seeded.
insert into public.states (id, name) values ('lagos', 'Lagos') on conflict do nothing;
insert into public.cities (id, state_id, name) values ('lagos', 'lagos', 'Lagos') on conflict do nothing;
insert into public.local_government_areas (id, state_id, name) values
${lgas.map((l) => `  (${q("lagos-" + slug(l))}, 'lagos', ${q(l)})`).join(",\n")}
on conflict do nothing;
insert into public.neighbourhoods (id, name, city_id, lga_id, centroid, aliases) values
${AREAS.map((a) => `  (${q(a.id)}, ${q(a.name)}, 'lagos', ${q("lagos-" + slug(a.lga))}, st_setsrid(st_makepoint(${a.lng}, ${a.lat}), 4326)::geography, array[${(a.aliases ?? []).map(q).join(", ")}]::text[])`).join(",\n")}
on conflict (id) do update set name = excluded.name, lga_id = excluded.lga_id, centroid = excluded.centroid, aliases = excluded.aliases, updated_at = now();
`;
writeFileSync(new URL("../supabase/migrations/20261113000100_seed_lagos.sql", import.meta.url), sql);
console.log(`Wrote ${AREAS.length} neighbourhoods across ${lgas.length} LGAs`);
